const staticPattern=new RegExp(Object.keys(ENGLISH_UI).sort((a,b)=>b.length-a.length).map(escaped).join('|'),'gu');
export function t(source,language=uiLanguage()){
 const text=String(source??'');if(language==='th')return text;
 return Object.hasOwn(ENGLISH_UI,text)?ENGLISH_UI[text]:text.replace(staticPattern,match=>ENGLISH_UI[match]);
}
export function html(parts,...values){return parts.map((part,index)=>t(part)+(index<values.length?values[index]:'')).join('');}
